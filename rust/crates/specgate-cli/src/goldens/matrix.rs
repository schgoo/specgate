/// Enforce unique rows and complete required language/variant coverage.
pub(super) fn check_shape(matrix: &Matrix) {
    let mut ids = HashSet::with_capacity(matrix.rows.len());
    let mut components = BTreeSet::new();
    for row in &matrix.rows {
        assert!(ids.insert(row.id.clone()), "duplicate matrix row id '{}'", row.id);
        assert!(
            !row.id.starts_with('/') && !row.id.ends_with('/') && !row.id.contains("..") && !row.id.contains('\\'),
            "matrix row id '{}' must be a relative forward-slash artifact path",
            row.id
        );
        assert!(!row.source_group.is_empty(), "row '{}' must declare a source group", row.id);
        check_checks(row);
        if row.parity.mode != ParityMode::ByteIdentical {
            assert!(
                row.parity.reason.as_ref().is_some_and(|reason| !reason.is_empty()),
                "row '{}' parity mode '{:?}' requires an explicit reason",
                row.id,
                row.parity.mode
            );
        }
        if row.parity.mode == ParityMode::Exception {
            assert!(
                !row.parity.allowed_differences.is_empty(),
                "row '{}' is a parity exception and must declare the exact differences it allows",
                row.id
            );
            let mut declared = BTreeSet::new();
            for difference in &row.parity.allowed_differences {
                assert!(
                    difference.path.starts_with('/'),
                    "row '{}' declares parity difference path '{}', which is not a JSON Pointer",
                    row.id,
                    difference.path
                );
                assert!(
                    difference.rust != difference.csharp,
                    "row '{}' declares an identical parity difference at '{}'",
                    row.id,
                    difference.path
                );
                assert!(
                    declared.insert(difference.render()),
                    "row '{}' declares the same parity difference twice at '{}'",
                    row.id,
                    difference.path
                );
            }
        } else {
            assert!(
                row.parity.allowed_differences.is_empty(),
                "row '{}' declares parity differences but its mode is '{:?}'",
                row.id,
                row.parity.mode
            );
        }
        assert_eq!(
            row.captures_any(),
            row.linkage_mode() == LinkageMode::Linked,
            "row '{}' must declare linkage 'linked' exactly when it captures a bundle",
            row.id
        );
        for (language_name, language) in [("rust", row.rust.as_ref()), ("csharp", row.csharp.as_ref())]
            .into_iter()
            .filter_map(|(name, language)| language.map(|language| (name, language)))
        {
            assert!(
                !language.binding.is_empty(),
                "row '{}' has an empty {language_name} implementation",
                row.id
            );
            assert!(!language.phases.is_empty(), "row '{}' must declare at least one phase", row.id);
        }
        match row.classification {
            Classification::ImplementationComponent => {
                let component = row
                    .component
                    .as_ref()
                    .unwrap_or_else(|| panic!("row '{}' must name a component", row.id));
                assert!(
                    components.insert(component.clone()),
                    "component '{component}' is covered by more than one matrix row"
                );
                assert_eq!(
                    row.id.as_str(),
                    format!("component/{component}"),
                    "component row id must be 'component/<component>'"
                );
                assert!(
                    row.implementations().next().is_some(),
                    "component row '{}' needs implementation coverage",
                    row.id
                );
                assert!(!row.sources.is_empty(), "component row '{}' must list its sources", row.id);
                for (name, implementation) in row.implementations() {
                    assert!(implementation.succeeds(), "component row '{}' must succeed", row.id);
                    assert!(
                        implementation.phases.contains(&Phase::Discover),
                        "component row '{}' must discover {name}",
                        row.id
                    );
                }
            }
            Classification::NegativeFixture => {
                assert!(row.id.starts_with("negative/"), "negative row id must start with 'negative/'");
                assert!(!row.sources.is_empty(), "negative row '{}' must list its sources", row.id);
                let language = row
                    .rust
                    .as_ref()
                    .unwrap_or_else(|| panic!("negative row '{}' needs Rust coverage", row.id));
                assert!(!language.succeeds(), "negative row '{}' must expect failure", row.id);
                assert_eq!(
                    language.error_artifacts(),
                    vec![RepoPath::from_path(error_file()).expect("error artifact name must be portable")],
                    "negative row '{}' must produce exactly {}",
                    row.id,
                    error_file().display()
                );
            }
            Classification::Replacement => {
                assert!(
                    row.id.starts_with("replacement/"),
                    "replacement row id must start with 'replacement/'"
                );
                assert!(
                    row.rust.is_none() && row.csharp.is_none(),
                    "replacement row '{}' owns no artifacts",
                    row.id
                );
                let replacement = row
                    .replacement
                    .as_ref()
                    .unwrap_or_else(|| panic!("replacement row '{}' must describe what it replaces", row.id));
                assert!(!replacement.feature.is_empty(), "replacement row '{}' needs a feature", row.id);
                assert!(!replacement.rationale.is_empty(), "replacement row '{}' needs a rationale", row.id);
                assert!(
                    !replacement.references.is_empty(),
                    "replacement row '{}' must point at CTSC-native tests",
                    row.id
                );
            }
        }
        for limitation in &row.limitations {
            assert!(
                !limitation.code.is_empty() && !limitation.detail.is_empty(),
                "row '{}' declares an empty limitation",
                row.id
            );
            assert!(
                limitation.code != ASYNC_LIMITATION || !row.captures_rust(),
                "row '{}' declares '{ASYNC_LIMITATION}' and must stay discovery-only",
                row.id
            );
        }
        assert!(
            row.capture_exclusions.is_empty() || row.classification == Classification::ImplementationComponent && row.captures_any(),
            "row '{}' may declare captureExclusions only for a captured component",
            row.id
        );
        let mut excluded_operations = BTreeSet::new();
        for exclusion in &row.capture_exclusions {
            assert!(
                !exclusion.operation.is_empty() && is_stable(&exclusion.code) && !exclusion.reason.is_empty(),
                "row '{}' declares an invalid capture exclusion; operation, stable code, and reason are required",
                row.id
            );
            assert!(
                excluded_operations.insert(exclusion.operation.as_str()),
                "row '{}' excludes capture of operation '{}' more than once",
                row.id,
                exclusion.operation
            );
        }
    }
    check_ownership(matrix).expect("invalid generated output ownership");
}

/// Ownership cannot escape the reserved generated namespace or collide with
/// handwritten sources. Row identities never determine producer scratch paths.
pub(super) fn check_ownership(matrix: &Matrix) -> Result<(), GoldenError> {
    let mut directories = BTreeSet::new();
    for row in &matrix.rows {
        let directory = match (&row.artifact_directory, row.classification) {
            (None, Classification::Replacement) => continue,
            (Some(directory), Classification::ImplementationComponent | Classification::NegativeFixture) => directory,
            _ => return Err(GoldenError::message(format!("{}: invalid artifact directory ownership", row.id))),
        };
        let required = match row.classification {
            Classification::ImplementationComponent => {
                format!("behavior/cases/{}/expected", row.component.as_deref().expect("component identity"))
            }
            Classification::NegativeFixture => format!(
                "rejection/rust/specgate-ctsc-negative-fixtures/expected/{}",
                row.id.strip_prefix("negative/").expect("negative identity")
            ),
            Classification::Replacement => unreachable!(),
        };
        if directory.as_str() != required {
            return Err(GoldenError::message(format!("{}: output ownership must be '{required}'", row.id)));
        }
        let key = directory.to_ascii_lowercase();
        if directories
            .iter()
            .any(|owned: &String| key == *owned || key.starts_with(&format!("{owned}/")) || owned.starts_with(&format!("{key}/")))
        {
            return Err(GoldenError::message(format!(
                "duplicate or overlapping output ownership: {directory}"
            )));
        }
        directories.insert(key);
        let owned = format!("{}/{directory}", matrix.artifact_root).to_ascii_lowercase();
        let collides = |source: &RepoPath| {
            let source = source.to_ascii_lowercase();
            source == owned || source.starts_with(&format!("{owned}/"))
        };
        if matrix.rows.iter().flat_map(|row| &row.sources).any(collides)
            || matrix
                .sources
                .exclusions
                .iter()
                .flat_map(|exclusion| &exclusion.paths)
                .any(collides)
        {
            return Err(GoldenError::message(format!("output/source collision: {directory}")));
        }
    }
    Ok(())
}

/// Validate one selected native reference and its directed checks before builds.
fn check_checks(row: &Row) {
    let mut implementations = BTreeSet::new();
    for (_, implementation) in row.implementations() {
        assert!(
            implementations.insert(&implementation.binding),
            "row '{}' has duplicate implementation endpoints",
            row.id
        );
    }
    if let Some(reference) = &row.reference {
        assert_eq!(
            row.classification,
            Classification::ImplementationComponent,
            "row '{}': only component rows may select a reference",
            row.id
        );
        let (_, implementation) = row.implementation(&reference.implementation).unwrap_or_else(|| {
            panic!(
                "row '{}' has unknown selected reference implementation '{}'",
                row.id, reference.implementation
            )
        });
        assert!(
            implementation.succeeds() && implementation.phases.contains(&Phase::Discover),
            "row '{}' selected reference '{}' has no successful discovery",
            row.id,
            reference.implementation
        );
        let artifacts = if row.captures_any() {
            assert!(
                implementation.phases.contains(&Phase::Capture),
                "row '{}' selected reference '{}' has no successful capture",
                row.id,
                reference.implementation
            );
            assert!(!row.checks.is_empty(), "row '{}' is missing checks for selected reference", row.id);
            vec![manifest_file(), trace_file(), registry_file()]
        } else {
            assert!(row.checks.is_empty(), "row '{}' discovery-only component owns no checks", row.id);
            vec![registry_file()]
        };
        assert_eq!(
            reference.artifacts,
            artifacts
                .into_iter()
                .map(|file| RepoPath::from_path(file).expect("portable artifact"))
                .collect::<Vec<_>>(),
            "row '{}' declares the wrong reference artifact set",
            row.id
        );
    } else {
        assert_ne!(
            row.classification,
            Classification::ImplementationComponent,
            "row '{}' must select a reference",
            row.id
        );
        assert!(row.checks.is_empty(), "row '{}' has checks without a selected reference", row.id);
    }
    let mut endpoints = BTreeSet::new();
    for check in &row.checks {
        assert!(
            endpoints.insert((&check.reference, &check.candidate)),
            "row '{}' has duplicate check endpoints",
            row.id
        );
        let (_, reference) = row
            .implementation(&check.reference)
            .unwrap_or_else(|| panic!("row '{}' has unknown reference implementation '{}'", row.id, check.reference));
        assert!(
            reference.succeeds() && reference.phases.contains(&Phase::Capture),
            "row '{}' reference '{}' has no successful capture",
            row.id,
            check.reference
        );
        assert_eq!(
            check.reference,
            row.reference.as_ref().expect("checks require a selected reference").implementation,
            "row '{}' check reference does not equal selected reference",
            row.id
        );
        let (_, candidate) = row
            .implementation(&check.candidate)
            .unwrap_or_else(|| panic!("row '{}' has unknown candidate implementation '{}'", row.id, check.candidate));
        assert!(
            candidate.succeeds() && candidate.phases.contains(&Phase::Discover),
            "row '{}' candidate '{}' is unavailable",
            row.id,
            check.candidate
        );
        if check.mode != ReplayMode::Verified {
            assert!(
                check.reason.as_ref().is_some_and(|reason| !reason.is_empty()),
                "row '{}' non-verified check requires an explicit reason",
                row.id
            );
        }
        if check.mode == ReplayMode::Unsupported {
            let category = check
                .expect_category
                .as_deref()
                .unwrap_or_else(|| panic!("row '{}' unsupported check must declare expectCategory", row.id));
            assert!(
                REPLAY_FAILURES.contains(&category),
                "row '{}' declares unknown replay failure category '{category}'",
                row.id
            );
        } else {
            assert!(check.expect_category.is_none(), "row '{}' has stale replay expectCategory", row.id);
        }
    }
}
